const fs = require("fs");
const path = require("path");

const data = JSON.parse(fs.readFileSync(path.join(__dirname, "tn.geojson"), "utf8"));

const PAD = 16;
const VIEW_W = 600;
const VIEW_H = 800;

let minLng = Infinity, maxLng = -Infinity, minLat = Infinity, maxLat = -Infinity;
for (const f of data.features) {
  const geom = f.geometry;
  const polys = geom.type === "Polygon" ? [geom.coordinates] : geom.coordinates;
  for (const poly of polys) {
    for (const ring of poly) {
      for (const [lng, lat] of ring) {
        if (lng < minLng) minLng = lng;
        if (lng > maxLng) maxLng = lng;
        if (lat < minLat) minLat = lat;
        if (lat > maxLat) maxLat = lat;
      }
    }
  }
}

const spanLng = maxLng - minLng;
const spanLat = maxLat - minLat;
const scale = Math.min((VIEW_W - PAD * 2) / spanLng, (VIEW_H - PAD * 2) / spanLat);
const usedW = spanLng * scale;
const usedH = spanLat * scale;
const offsetX = (VIEW_W - usedW) / 2;
const offsetY = (VIEW_H - usedH) / 2;

function project([lng, lat]) {
  const x = offsetX + (lng - minLng) * scale;
  const y = offsetY + (maxLat - lat) * scale; // flip: lat up -> y down
  return [Math.round(x * 100) / 100, Math.round(y * 100) / 100];
}

function ringToPath(ring) {
  const pts = ring.map(project);
  return "M" + pts.map((p) => p.join(",")).join("L") + "Z";
}

// simple polygon area (shoelace) for picking the largest ring as "main body"
function ringArea(ring) {
  let area = 0;
  for (let i = 0; i < ring.length; i++) {
    const [x1, y1] = ring[i];
    const [x2, y2] = ring[(i + 1) % ring.length];
    area += x1 * y2 - x2 * y1;
  }
  return Math.abs(area / 2);
}

const districts = data.features.map((f) => {
  const geom = f.geometry;
  const polys = geom.type === "Polygon" ? [geom.coordinates] : geom.coordinates;

  // Each poly's first ring is its outer boundary; project all, build path,
  // and track the largest ring (by projected area) for a sane centroid.
  let d = "";
  let largest = { area: -1, pts: null };
  for (const poly of polys) {
    const outer = poly[0];
    const projected = outer.map(project);
    d += ringToPath(outer);
    const area = ringArea(projected);
    if (area > largest.area) largest = { area, pts: projected };
  }

  const pts = largest.pts;
  const cx = pts.reduce((s, p) => s + p[0], 0) / pts.length;
  const cy = pts.reduce((s, p) => s + p[1], 0) / pts.length;

  return {
    name: f.properties.NAME_2.replace(/\s+Kattabo$/, ""), // dataset typo cleanup
    path: d,
    cx: Math.round(cx * 100) / 100,
    cy: Math.round(cy * 100) / 100,
  };
});

districts.sort((a, b) => a.name.localeCompare(b.name));

const out = `// Auto-generated by scripts/build-tn-districts.js — do not hand-edit.
// Source: India-D3 TamilNadu.geojson (district-level boundaries), simple
// equirectangular projection into a ${VIEW_W}x${VIEW_H} viewBox.
// NOTE: this dataset has ${districts.length} districts (the older, pre-2019
// division) rather than the current ~38 — the newer split isn't available
// as an open dataset we could verify, so we're using accurate real
// boundaries for ${districts.length} districts rather than fabricating the
// newer ones.

export const TN_MAP_VIEWBOX = { width: ${VIEW_W}, height: ${VIEW_H} };

export interface TNDistrict {
  name: string;
  path: string;
  cx: number;
  cy: number;
}

export const TN_DISTRICTS: TNDistrict[] = ${JSON.stringify(districts, null, 2)};
`;

fs.writeFileSync(path.join(__dirname, "..", "src", "lib", "tn-districts.ts"), out);
console.log(`Wrote ${districts.length} districts.`);
