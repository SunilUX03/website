type IdRow = { id?: string | null };

function zip<T extends IdRow, V>(en: T[] | null | undefined, values: V[]): (V & { id?: string })[] {
  return values.map((v, i) => {
    const id = en?.[i]?.id;
    return id ? { ...(v as object), id } : (v as object);
  }) as (V & { id?: string })[];
}

